#!/usr/bin/env python3
"""Write the WHATWG named character reference table as a MoonBit array.

The table is the one in the HTML standard's "named character references"
section, which is what every browser decodes. Names that may appear without a
semicolon are in it twice — `amp` and `amp;` — because the tokenizer's
longest-match rule has to see both spellings.

Usage: python3 scripts/gen_entities.py <out.mbt>
"""

import html.entities
import sys


def escape(value):
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def main():
    out_path = sys.argv[1]
    rows = sorted(html.entities.html5.items())
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by scripts/gen_entities.py — do not edit.\n")
        handle.write("// The named character references of the HTML standard.\n\n")
        handle.write("///|\n/// Every named character reference, sorted by name for the\n")
        handle.write("/// longest-match search: a name with no `;` may be written without\n")
        handle.write("/// one, which is why some names appear twice.\n")
        handle.write("let named_table : Array[(String, String)] = [\n")
        for name, value in rows:
            handle.write('  ("%s", "%s"),\n' % (escape(name), escape(value)))
        handle.write("]\n")
    print("%d references written to %s" % (len(rows), out_path))


if __name__ == "__main__":
    main()
