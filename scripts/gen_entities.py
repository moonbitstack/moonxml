#!/usr/bin/env python3
"""Generate html/entities.mbt from Python's WHATWG named character reference table.

Python ships `html.entities.html5`, a dict of every named reference with and
without its trailing semicolon. Emitting one `match` arm per name keeps lookup
allocation-free in MoonBit and makes the table trivially diffable.

Usage:
    python scripts/gen_entities.py
"""

from html.entities import html5
from pathlib import Path


def moonbit_char(ch: str) -> str:
    cp = ord(ch)
    if ch == "\\":
        return "\\\\"
    if ch == '"':
        return '\\"'
    if ch == "\n":
        return "\\n"
    if ch == "\r":
        return "\\r"
    if ch == "\t":
        return "\\t"
    if 0x20 <= cp < 0x7F:
        return ch
    return "\\u{%X}" % cp


def main() -> None:
    out = [
        "/// Generated by `scripts/gen_entities.py` from Python's",
        "/// `html.entities.html5`: the full WHATWG named character reference table,",
        "/// with and without the trailing semicolon. A `match` keeps lookup",
        "/// allocation-free. Do not edit by hand; regenerate instead.",
        "fn entity_value(name : String) -> String? {",
        "  match name {",
    ]
    for name, value in sorted(html5.items()):
        escaped_name = name.replace("\\", "\\\\").replace('"', '\\"')
        escaped_value = "".join(moonbit_char(c) for c in value)
        out.append('    "%s" => Some("%s")' % (escaped_name, escaped_value))
    out.append("    _ => None")
    out.append("  }")
    out.append("}")
    out.append("")

    target = Path(__file__).resolve().parent.parent / "html" / "entities.mbt"
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote %s (%d entries)" % (target, len(html5)))


if __name__ == "__main__":
    main()
