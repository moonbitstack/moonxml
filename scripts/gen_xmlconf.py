#!/usr/bin/env python3
"""Turn the W3C XML conformance suite into a MoonBit fixture.

The suite is a tree of catalogues, each listing `<TEST URI TYPE>` entries: a
document and what a conformant processor must make of it. `valid` and
`invalid` documents are well-formed and must be read; `not-wf` documents are
not, and must be refused. `error` entries are the suite's optional errors and
are left out, as is everything that is XML 1.1 or that is not UTF-8 — this
reader takes UTF-8 in.

Usage: python3 scripts/gen_xmlconf.py <xmlconf-dir> <out.mbt>
"""

import os
import re
import sys

# Every catalogue the top-level one includes, minus the XML 1.1 suites.
CATALOGUES = [
    "sun/sun-valid.xml",
    "sun/sun-invalid.xml",
    "sun/sun-not-wf.xml",
    "xmltest/xmltest.xml",
    "japanese/japanese.xml",
    "oasis/oasis.xml",
    "ibm/ibm_oasis_valid.xml",
    "ibm/ibm_oasis_invalid.xml",
    "ibm/ibm_oasis_not-wf.xml",
    "eduni/errata-2e/errata2e.xml",
    "eduni/errata-3e/errata3e.xml",
    "eduni/namespaces/1.0/rmt-ns10.xml",
]

TEST = re.compile(r"<TEST\s+([^>]*)>", re.S)
ATTR = re.compile(r"(\w+)\s*=\s*\"([^\"]*)\"")

KINDS = {"valid": "pass", "invalid": "pass", "not-wf": "refuse"}

# Cases this fixture leaves out, and why, in the three groups they fall into.
#
# 1. The fault lives in a file beside the document — an external subset, an
#    external parameter entity, or an external entity's content. Reading those
#    is I/O, which this library does not do; a case whose whole defect is in a
#    file nobody opened cannot be judged, so it is not counted.
# 2. The suite was written against XML 1.0 fourth edition in places and this
#    reader follows the fifth, which is the current recommendation: a character
#    that Unicode 2.0 had no letter for is a name character now, so the reader
#    accepts these documents on purpose. Every one of them says so in a comment
#    naming the "illegal char" it is about.
# 3. Namespaces 1.0 makes a lone `:` a namespace error; the suite's
#    namespace-unaware files count it as a name.
EXCLUDE = [
    "ibm/not-wf/P30/",
    "ibm/not-wf/P31/",
    "ibm/not-wf/P41/ibm41n11.xml",
    "ibm/not-wf/P61/",
    "ibm/not-wf/P62/",
    "ibm/not-wf/P63/",
    "ibm/not-wf/P64/",
    "ibm/not-wf/P65/",
    "ibm/not-wf/P77/",
    "ibm/not-wf/P78/",
    "ibm/not-wf/P79/",
    "ibm/not-wf/p28a/",
    "ibm/not-wf/P85/",
    "ibm/not-wf/P86/",
    "ibm/not-wf/P87/",
    "ibm/not-wf/P88/",
    "ibm/not-wf/P89/",
    "eduni/errata-2e/E38.xml",
    "sun/not-wf/cond0",
    "sun/not-wf/decl01.xml",
    "sun/not-wf/dtd07.xml",
    "sun/not-wf/encoding07.xml",
    "xmltest/not-wf/not-sa/",
    "xmltest/not-wf/ext-sa/",
    "xmltest/not-wf/sa/140.xml",
    "xmltest/not-wf/sa/141.xml",
    "xmltest/not-wf/cond01.xml",
    "xmltest/valid/sa/012.xml",
]


def excluded(name):
    return any(name.startswith(prefix) for prefix in EXCLUDE)


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def main():
    source, out_path = sys.argv[1], sys.argv[2]
    seen = set()
    rows = []
    for catalogue in CATALOGUES:
        path = os.path.join(source, catalogue)
        if not os.path.exists(path):
            continue
        base = os.path.dirname(path)
        with open(path, encoding="utf-8", errors="replace") as handle:
            body = handle.read()
        for match in TEST.finditer(body):
            attrs = dict(ATTR.findall(match.group(1)))
            uri = attrs.get("URI")
            kind = KINDS.get(attrs.get("TYPE", ""))
            if not uri or not kind:
                continue
            document = os.path.normpath(os.path.join(base, uri))
            if document in seen or not os.path.exists(document):
                continue
            with open(document, "rb") as handle:
                data = handle.read()
            try:
                text = data.decode("utf-8")
            except UnicodeDecodeError:
                # An encoding test: this reader takes UTF-8 and nothing else.
                continue
            seen.add(document)
            name = os.path.relpath(document, source).replace("\\", "/")
            if excluded(name):
                continue
            rows.append((name, kind, text))

    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by scripts/gen_xmlconf.py — do not edit.\n")
        handle.write("// From the W3C XML conformance test suite.\n\n")
        handle.write(
            "///|\n/// (case name, what it asks for, the document). `pass` is a\n"
            "/// well-formed document; `refuse` is one that is not.\n"
        )
        handle.write("let conformance : Array[(String, String, String)] = [\n")
        for name, kind, text in rows:
            chunks = [text[i:i + 1000] for i in range(0, len(text), 1000)] or [""]
            body = " +\n    ".join('"%s"' % escape(chunk) for chunk in chunks)
            handle.write('  ("%s", "%s", %s),\n' % (escape(name), kind, body))
        handle.write("]\n")
    print("%d cases written to %s" % (len(rows), out_path))


if __name__ == "__main__":
    main()
