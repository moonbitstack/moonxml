#!/usr/bin/env python3
"""Turn html5lib's tree-construction corpus into a MoonBit fixture.

html5lib-tests writes each case as `#data`, an optional `#errors`, and
`#document` with the expected tree spelled one node per line. That is exactly
what `render` produces, so the fixture is the corpus verbatim, and a failure is
a diff.

Usage: python3 scripts/gen_html5lib.py <tree-construction-dir> <out.mbt>
"""

import os
import sys

# The files whose cases this parser claims to reproduce. The rest of the corpus
# covers features this library deliberately leaves out — template contents,
# framesets, foreign (SVG/MathML) integration points — and a fixture that
# counted them would only measure what is absent.
FILES = [
    # The document-parsing corpus, minus the files that cover what this version
    # leaves out: HTML foreign content (SVG and MathML integration points, in
    # tests9, 10, 11, 12, 19, math01 and namespace-sensitivity) and the
    # documents that predate the current insertion modes. See README, "What is
    # not here yet".
    "tests1.dat",
    "tests2.dat",
    "tests3.dat",
    "tests5.dat",
    "tests6.dat",
    "tests7.dat",
    "tests8.dat",
    "tests14.dat",
    "tests15.dat",
    "tests16.dat",
    "tests17.dat",
    "tests18.dat",
    "tests20.dat",
    "tests22.dat",
    "tests23.dat",
    "tables01.dat",
    "entities01.dat",
    "entities02.dat",
    "comments01.dat",
    "doctype01.dat",
    "domjs-unsafe.dat",
    "plain-text-unsafe.dat",
    "scriptdata01.dat",
    "webkit01.dat",
    "webkit02.dat",
    "adoption01.dat",
    "adoption02.dat",
    "blocks.dat",
    "inbody01.dat",
    "isindex.dat",
    "search-element.dat",
    "tricky01.dat",
]


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            continue
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def cases(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        body = handle.read()
    for chunk in body.split("#data\n")[1:]:
        data, rest = chunk.split("\n#errors", 1)
        if "#document\n" not in rest:
            continue
        # `#document-fragment` cases read a snippet in a context element, which
        # is `loads_fragment`'s job, not the document parser's.
        if "#document-fragment" in rest:
            continue
        expected = rest.split("#document\n", 1)[1]
        # the corpus separates cases with a blank line; the tree runs until it
        yield data, expected.rstrip("\n") + "\n"


def main():
    source, out_path = sys.argv[1], sys.argv[2]
    seen = set()
    rows = []
    for name in FILES:
        if name in seen:
            continue
        seen.add(name)
        path = os.path.join(source, name)
        if not os.path.exists(path):
            continue
        for k, (data, expected) in enumerate(cases(path)):
            rows.append((f"{name}:{k}", data, expected))

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("// Generated by scripts/gen_html5lib.py — do not edit.\n")
        handle.write("// From https://github.com/html5lib/html5lib-tests (MIT).\n\n")
        handle.write("///|\n/// (case name, source, expected tree in html5lib's own spelling).\n")
        handle.write("let corpus : Array[(String, String, String)] = [\n")
        for name, data, expected in rows:
            handle.write(
                '  ("%s", "%s", "%s"),\n'
                % (escape(name), escape(data), escape(expected))
            )
        handle.write("]\n")
    print(f"{len(rows)} cases written to {out_path}")


if __name__ == "__main__":
    main()
