#!/usr/bin/env python3
"""Generate MoonBit fixtures from the vendored html5lib tree-construction corpus.

The corpus format is documented in vendor/html5lib-tests/tree-construction/README.md.
Run from the repository root:

    python scripts/gen_html5lib.py

It writes tests/html5lib_cases.mbt. The fixtures are committed so CI needs no
network and no file I/O from MoonBit (core has no filesystem module).
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORPUS = ROOT / "vendor" / "html5lib-tests" / "tree-construction"
OUT = ROOT / "tests" / "html5lib_cases.mbt"


def parse_file(path: pathlib.Path):
    lines = path.read_text(encoding="utf-8").split("\n")
    i = 0
    n = len(lines)
    cases = []
    while i < n:
        if lines[i] != "#data":
            i += 1
            continue
        i += 1
        data = []
        while i < n and lines[i] != "#errors":
            data.append(lines[i])
            i += 1
        if i >= n:
            break
        i += 1  # #errors
        while i < n and lines[i] not in (
            "#document-fragment",
            "#script-off",
            "#script-on",
            "#document",
            "#new-errors",
        ):
            i += 1
        fragment = ""
        if i < n and lines[i] == "#new-errors":
            i += 1
            while i < n and lines[i] not in (
                "#document-fragment",
                "#script-off",
                "#script-on",
                "#document",
            ):
                i += 1
        if i < n and lines[i] == "#document-fragment":
            i += 1
            fragment = lines[i] if i < n else ""
            i += 1
        while i < n and lines[i] in ("#script-off", "#script-on"):
            i += 1
        if i >= n or lines[i] != "#document":
            i += 1
            continue
        i += 1
        doc = []
        while i < n and lines[i].startswith("| "):
            line = lines[i]
            i += 1
            # A text node may span lines: its content is everything up to the
            # closing quote, which can sit on a later line.
            content = line[2:].lstrip()
            if content.startswith('"') and not content.endswith('"'):
                parts = [line]
                while i < n:
                    parts.append(lines[i])
                    ended = lines[i].endswith('"')
                    i += 1
                    if ended:
                        break
                line = "\n".join(parts)
            doc.append(line)
        cases.append(
            {
                "file": path.name,
                "input": "\n".join(data),
                "fragment": fragment,
                "doc": "\n".join(doc),
            }
        )
        while i < n and lines[i] == "":
            i += 1
    return cases


def esc(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20:
            out.append("\\u{%X}" % o)
        else:
            out.append(ch)
    return "".join(out)


def main() -> int:
    cases = []
    for path in sorted(CORPUS.glob("*.dat")):
        cases.extend(parse_file(path))
    if not cases:
        print("no cases parsed", file=sys.stderr)
        return 1

    lines = [
        "/// Generated by scripts/gen_html5lib.py from the vendored html5lib-tests",
        "/// corpus. Do not edit by hand.",
        "",
        "pub struct H5Case {",
        "  file : String",
        "  input : String",
        "  fragment : String",
        "  doc : String",
        "}",
        "",
        "pub fn h5_cases() -> Array[H5Case] {",
        "  [",
    ]
    for c in cases:
        lines.append(
            '    { file: "%s", input: "%s", fragment: "%s", doc: "%s" },'
            % (esc(c["file"]), esc(c["input"]), esc(c["fragment"]), esc(c["doc"]))
        )
    lines.append("  ]")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %d cases to %s (%d bytes)" % (len(cases), OUT, OUT.stat().st_size))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
