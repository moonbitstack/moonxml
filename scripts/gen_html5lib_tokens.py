#!/usr/bin/env python3
"""Turn html5lib's tokenizer corpus into a MoonBit fixture.

Each case is one input fed to the tokenizer from a given state, and the answer is
the exact list of tokens. Every token is flattened to one string, so the test
compares lists of strings and a failure names the first that differs:

    c<data>                          characters
    s<name> <attr> <attr> [/]        start tag, attributes as name=value
    e<name>                          end tag
    m<data>                          comment
    d<name> <public> <system> <ok>   doctype, `~` for a value that is missing

Fields are separated by U+001F.

Left out: `xmlViolationTests`, which describe an XML infoset rather than tokenizing;
the processing instruction cases, since the specification has no such token and the
tree-construction corpus reads `<?x?>` as a comment; and the lone surrogates, which
pin JavaScript strings and cannot be written to a source file.

Usage: python3 scripts/gen_html5lib_tokens.py <tokenizer-dir> <out.mbt>
"""

import json
import pathlib
import sys

US = "\x1f"
# One literal holding all of them is more than a text segment can, and top-level
# ones overflow the locals of wasm's init function.
SIZE = 500
STATES = {
    "Data state": "Data",
    "PLAINTEXT state": "Plaintext",
    "RCDATA state": "Rcdata",
    "RAWTEXT state": "Rawtext",
    "Script data state": "ScriptData",
    "CDATA section state": "CdataSection",
}


def unescape_double(text):
    """Undo the extra level of `\\uHHHH` a `doubleEscaped` case asks for."""
    out = []
    at = 0
    while at < len(text):
        if text[at] == "\\" and at + 5 < len(text) and text[at + 1] == "u":
            try:
                out.append(chr(int(text[at + 2 : at + 6], 16)))
                at += 6
                continue
            except ValueError:
                pass
        out.append(text[at])
        at += 1
    return "".join(out)


def has_surrogate(text):
    return any(0xD800 <= ord(ch) <= 0xDFFF for ch in text)


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def field(value):
    return "~" if value is None else "=" + value


def token(tok):
    kind = tok[0]
    if kind == "Character":
        return "c" + tok[1]
    if kind == "Comment":
        return "m" + tok[1]
    if kind == "EndTag":
        return "e" + tok[1]
    if kind == "StartTag":
        parts = ["s" + tok[1]] + [k + "=" + v for k, v in tok[2].items()]
        if len(tok) > 3 and tok[3]:
            parts.append("/")
        return US.join(parts)
    if kind == "DOCTYPE":
        return US.join(["d" + field(tok[1]), field(tok[2]), field(tok[3]), "1" if tok[4] else "0"])
    raise SystemExit("unknown token: " + kind)


def cases_of(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    for test in data.get("tests", []):
        output = test["output"]
        if any(tok[0] == "ProcessingInstruction" for tok in output):
            continue
        if not output and test["input"].startswith("<?"):
            continue
        source = test["input"]
        if test.get("doubleEscaped"):
            source = unescape_double(source)
            output = [[unescape_double(v) if isinstance(v, str) else v for v in tok] for tok in output]
        if has_surrogate(source) or any(has_surrogate(v) for tok in output for v in tok if isinstance(v, str)):
            continue
        expected = [token(tok) for tok in output]
        for state in test.get("initialStates", ["Data state"]):
            yield path.name, test.get("description", ""), STATES[state], test.get("lastStartTag", "").lower(), source, expected


def main():
    corpus, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    rows = []
    for path in sorted(corpus.glob("*.test")):
        for name, about, state, last, source, expected in cases_of(path):
            listed = ", ".join('"%s"' % escape(tok) for tok in expected)
            rows.append('  ("%s", "%s", %s, "%s", "%s", [%s]),' % (name, escape(about), state, last, escape(source), listed))
    lines = [
        "// Generated by scripts/gen_html5lib_tokens.py — do not edit.",
        "// From https://github.com/html5lib/html5lib-tests (MIT).",
        "",
        "///|",
        "/// (file, what it tests, the state to start in, the last start tag, the source,",
        "/// the tokens in the spelling the generator writes down).",
        "type Case = (String, String, TokState, String, String, Array[String])",
    ]
    chunks = [rows[at : at + SIZE] for at in range(0, len(rows), SIZE)]
    for number, chunk in enumerate(chunks):
        lines += ["", "///|", "fn token_cases_%d() -> Array[Case] {" % number, "  ["] + chunk + ["  ]", "}"]
    lines += [
        "",
        "///|",
        "fn token_corpus() -> Array[Case] {",
        "  [%s]" % ", ".join("..token_cases_%d()" % n for n in range(len(chunks))),
        "}",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(rows), "cases")


main()
